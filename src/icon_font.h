// 글리프 인덱스: 0-9, '?', A-Z(소문자는 대문자로 접어서). 미수록 문자는 -1.
static inline int IconFont_Index(unsigned int c) {
    if (c >= 'a' && c <= 'z') c -= 'a' - 'A';
    if (c >= '0' && c <= '9') return (int)(c - '0');
    if (c == '?') return 10;
    if (c >= 'A' && c <= 'Z') return 11 + (int)(c - 'A');
    return -1;
}
